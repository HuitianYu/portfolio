import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const shared = [
  ["static/js/lab-interface.js", "lab-interface.js"],
  ["static/js/lab-runtime.js", "lab-runtime.js"],
  ["static/css/design-system.css", "design-system.css"],
];
let mismatches = 0;
const ui = JSON.parse(await fs.readFile(path.join(root, "data/lab-ui.json"), "utf8"));
const formatting = JSON.parse(await fs.readFile(path.join(root, ".prettierrc.json"), "utf8"));
for (const lab of await fs.readdir(path.join(root, "content/labs"), { withFileTypes: true })) {
  if (!lab.isDirectory()) continue;
  const frontmatter = await fs.readFile(
    path.join(root, "content/labs", lab.name, "index.md"),
    "utf8",
  );
  const metadata = JSON.parse(frontmatter.split("---")[1]);
  const config = { id: metadata.id, name: metadata.title, data: metadata.data || {}, ui };
  const generated = await prettier.format(
    "// Generated by tools/sync-shared.mjs; edit Lab frontmatter or data/lab-ui.json.\n" +
      "window.LAB_CONFIG = " +
      JSON.stringify(config) +
      ";\n",
    { ...formatting, parser: "babel" },
  );
  const configPath = path.join(root, "content/labs", lab.name, "ui/lab-config.js");
  if ((await fs.readFile(configPath, "utf8").catch(() => "")) !== generated) {
    mismatches++;
    if (check) console.error(`Offline configuration differs: ${lab.name}`);
    else await fs.writeFile(configPath, generated);
  }

  for (const [source, filename] of shared) {
    const target = path.join(root, "content/labs", lab.name, "ui", filename);
    const canonical = await fs.readFile(path.join(root, source));
    const existing = await fs.readFile(target).catch(() => null);
    if (existing?.equals(canonical)) continue;
    mismatches++;
    if (check) console.error(`Shared file differs: ${lab.name}/${filename}`);
    else await fs.writeFile(target, canonical);
  }
}
console.log(`${mismatches} shared copies ${check ? "differ" : "synchronized"}.`);
if (check && mismatches) process.exitCode = 1;
