/** Keep browser delivery flat and offline-safe; edit only ui/styles source modules. */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const manifest = JSON.parse(await fs.readFile(path.join(root, "ui/styles/manifest.json"), "utf8"));
const options = JSON.parse(await fs.readFile(path.join(root, ".prettierrc.json"), "utf8"));
let changed = 0;
for (const [output, modules] of Object.entries(manifest)) {
  const parts = await Promise.all(
    modules.map(async (module) => {
      if (!module.startsWith("ui/styles/") || module.includes(".."))
        throw Error(`Invalid style module: ${module}`);
      return `/* Source: ${module} */\n${await fs.readFile(path.join(root, module), "utf8")}`;
    }),
  );
  const css = await prettier.format(
    "/* Generated by tools/build-styles.mjs. Do not edit this file. */\n" + parts.join("\n"),
    { ...options, parser: "css" },
  );
  const target = path.join(root, output);
  if ((await fs.readFile(target, "utf8")) === css) continue;
  changed++;
  if (check) console.error(`Stylesheet differs: ${output}`);
  else await fs.writeFile(target, css);
}
console.log(`${changed} stylesheets ${check ? "differ" : "built"}.`);
if (check && changed) process.exitCode = 1;
